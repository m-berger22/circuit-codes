for x in itertools.product(range(B+1),repeat=6):
    if sum(x)>B: continue
    nm='x%s_%s'%(NAME,''.join(map(str,x))); names.append(nm)
    out.append('theorem %s : dfs par%s (xfun %s) [] %d 0 0 0 = false := by'%(nm,NAME,' '.join(map(str,x)),N))
    gen(x,N,0,0,0,0,'  ')
    out.append('')
print('\n'.join(out))
print('theorem noSol%s : NoSol par%s := by'%(NAME,NAME))
print('  intro x0 x1 x2 x3 x4 x5 hx')
print('  have hx\' : x0 + x1 + x2 + x3 + x4 + x5 ≤ %d := hx'%B)
