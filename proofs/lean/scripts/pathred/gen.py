# gen.py NAME par d1 d2 d3 d4 M E B TH > Ccformal/PathReducedNAME.lean
# generates the split kernel-decide proof of NoSol parNAME (adaptive split of the DFS tree: subtrees with <= TH nodes
# are one `decide +kernel`, bigger ones are split by candidate number with dfs_split).
import sys, itertools
NAME=sys.argv[1]; args=sys.argv[2:10]; TH=int(sys.argv[10])
src=open(__file__.replace('gen.py','twin2.py')).read().split('N=5*M;')[0]
sys.argv=['twin2.py']+args
exec(src)
N=5*M
def cands(s,TY):
    if dummy(s): return [(0,0,s)]
    return [(q,2*q,s) for q in range(16)]+[(16+t,gty(TY,t),t) for t in range(s)]
def count(x,n,s,TY,ID):
    if n==0: raise SystemExit('SOLUTION FOUND')
    tot=0 if dummy(s) else 1
    for c,ty,i in cands(s,TY):
        TY2=TY+ty*32**s; ID2=ID+i*32**s
        if stepok(x,s,lambda t:(gty(TY2,t),gty(ID2,t))): tot+=count(x,n-1,s+1,TY2,ID2)
    return tot
out=[]; nleaf=[0]
def gen(x,n,s,TY,ID,depth,ind):
    # proves dfs par x sel n0 0 0 0 = false where the selector prefix leads to state (n,s,TY,ID)
    if count(x,n,s,TY,ID)<=TH:
        out.append(ind+'decide +kernel'); nleaf[0]+=1; return
    bound=16+depth
    out.append(ind+'apply dfs_split')
    out.append(ind+'intro c hc')
    out.append(ind+'replace hc : c < %d := by simpa using hc'%bound)
    out.append(ind+'interval_cases c')
    cd={c:(ty,i) for c,ty,i in cands(s,TY)}
    for c in range(bound):
        ok=False
        if c in cd:
            ty,i=cd[c]; TY2=TY+ty*32**s; ID2=ID+i*32**s
            ok=stepok(x,s,lambda t:(gty(TY2,t),gty(ID2,t)))
        if ok:
            out.append(ind+'·')
            gen(x,n-1,s+1,TY2,ID2,depth+1,ind+'  ')
        else:
            out.append(ind+'· decide +kernel'); nleaf[0]+=1
print('''import Ccformal.PathReduced

/-! Generated by `scripts/pathred/gen.py %s` : the reduced model `par%s` has no solution
(kernel evaluation of the exhaustive search, split over many small `decide +kernel` calls). -/

namespace Coil

namespace Red

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option linter.unusedTactic false
set_option linter.unreachableTactic false

def par%s : Params := ⟨%s⟩
'''%(' '.join(sys.argv[1:]+[NAME]+args+[str(TH)]) if False else NAME+' '+' '.join(args)+' '+str(TH),NAME,NAME,', '.join(args)))
